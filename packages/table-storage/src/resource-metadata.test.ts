import assert from "node:assert/strict";
import { test } from "node:test";
import { newId, type Actor } from "@rootset/contracts";
import { withOrg } from "@rootset/database";
import { isolatedDatabase } from "../../../tools/verification/isolated-database";
import { TableStorage } from "./index";

test(
  "resource summaries count live records and fields and track only committed data changes",
  { skip: !process.env.ROOTSET_TEST_DATABASE_URL },
  async (t) => {
    const fixture = await isolatedDatabase();
    t.after(() => fixture.close());
    const actor: Actor = {
      id: newId(),
      orgId: newId(),
      kind: "operator",
      role: "admin",
      scopes: ["viewer", "member", "admin"],
    };
    await fixture.owner.query(
      "INSERT INTO rootset_control.organisations(id,name) VALUES($1,'Resource metadata')",
      [actor.orgId],
    );
    const storage = new TableStorage({
      pool: fixture.app,
      ddlPool: fixture.ddl,
      cursorSecret: "resource-metadata-tests-secret-over-thirty-two-bytes",
    });
    const database = await storage.createDatabase(actor, {
      name: "Inventory",
      description: "Shared reference data",
    });
    let first = await storage.createTable(actor, database.id, {
      name: "Aircraft",
      description: "Aircraft specifications",
      fields: [{ name: "NAME", type: "text", charLimit: 20 }],
    });
    const second = await storage.createTable(actor, database.id, {
      name: "Manufacturers",
      fields: [{ name: "NAME", type: "text" }],
    });
    const tableSummary = async (id: string) =>
      (await storage.listTables(actor, database.id)).find(
        (table) => table.id === id,
      )!;
    const databaseSummary = async () =>
      (await storage.listDatabases(actor)).find(
        (entry) => entry.id === database.id,
      )!;
    assert.equal((await tableSummary(first.id)).lastDataChangeAt, null);
    assert.equal((await tableSummary(first.id)).fieldCount, 1);
    assert.equal(
      (await tableSummary(first.id)).description,
      "Aircraft specifications",
    );
    assert.equal((await databaseSummary()).rowCount, 0);
    assert.equal((await databaseSummary()).lastDataChangeAt, null);
    assert.equal(
      (await databaseSummary()).description,
      "Shared reference data",
    );

    const idempotencyKey = newId();
    const row = await storage.createRow(
      actor,
      first.id,
      { NAME: null },
      { idempotencyKey },
    );
    const createdAt = (await tableSummary(first.id)).lastDataChangeAt!;
    assert.ok(Number.isFinite(Date.parse(createdAt)));
    assert.equal((await databaseSummary()).lastDataChangeAt, createdAt);
    assert.equal((await databaseSummary()).rowCount, 1);
    await storage.createRow(
      actor,
      first.id,
      { NAME: null },
      { idempotencyKey },
    );
    await storage.updateRow(
      actor,
      first.id,
      row.id,
      { NAME: null },
      { expectedVersion: row.version },
    );
    assert.equal((await tableSummary(first.id)).lastDataChangeAt, createdAt);
    await assert.rejects(
      storage.mutateRows(actor, first.id, {
        operations: [
          {
            kind: "update",
            rowId: row.id,
            values: { NAME: "Rolled back" },
            expectedVersion: row.version,
          },
          { kind: "create", values: { NAME: "x".repeat(21) } },
        ],
      }),
      { code: "VALIDATION_FAILED" },
    );
    assert.equal((await tableSummary(first.id)).lastDataChangeAt, createdAt);
    assert.equal((await tableSummary(first.id)).rowCount, 1);

    first = await storage.createField(actor, first.id, {
      name: "NOTE",
      type: "text",
      default: "Generated by schema",
      expectedSchemaVersion: first.schemaVersion,
    });
    assert.equal((await tableSummary(first.id)).fieldCount, 2);
    assert.equal((await tableSummary(first.id)).lastDataChangeAt, createdAt);
    const current = await storage.getRow(actor, first.id, row.id);
    await storage.updateRow(
      actor,
      first.id,
      row.id,
      { NAME: null },
      { expectedVersion: current.version },
    );
    assert.equal((await tableSummary(first.id)).lastDataChangeAt, createdAt);
    first = await storage.deleteField(
      actor,
      first.id,
      first.fields.find((field) => field.name === "NOTE")!.id,
      { expectedSchemaVersion: first.schemaVersion },
    );
    await storage.updateTable(actor, first.id, {
      description: "Updated description",
      expectedSchemaVersion: first.schemaVersion,
    });
    await storage.updateDatabase(actor, database.id, {
      name: "Renamed inventory",
    });
    assert.equal((await tableSummary(first.id)).fieldCount, 1);
    assert.equal((await tableSummary(first.id)).lastDataChangeAt, createdAt);
    assert.equal((await databaseSummary()).lastDataChangeAt, createdAt);

    const changed = await storage.updateRow(
      actor,
      first.id,
      row.id,
      { NAME: "Changed" },
      { expectedVersion: current.version },
    );
    assert.ok((await tableSummary(first.id)).lastDataChangeAt! > createdAt);
    await storage.mutateRows(actor, second.id, {
      operations: [
        { kind: "create", values: { NAME: "One" } },
        { kind: "create", values: { NAME: "Two" } },
      ],
      context: { source: "import" },
    });
    const importedAt = (await tableSummary(second.id)).lastDataChangeAt!;
    assert.ok(importedAt);
    assert.equal((await databaseSummary()).rowCount, 3);
    assert.equal((await databaseSummary()).lastDataChangeAt, importedAt);
    await storage.deleteRow(actor, first.id, changed.id, {
      expectedVersion: changed.version,
    });
    const deletedAt = (await tableSummary(first.id)).lastDataChangeAt!;
    assert.ok(deletedAt > createdAt);
    assert.equal((await tableSummary(first.id)).rowCount, 0);
    assert.equal((await databaseSummary()).rowCount, 2);
    assert.equal((await databaseSummary()).lastDataChangeAt, deletedAt);
    assert.equal(
      (
        await withOrg(fixture.app, actor.orgId, (client) =>
          client.query(
            "SELECT count(*)::int AS count FROM rootset_control.cell_changes WHERE table_id=$1",
            [first.id],
          ),
        )
      ).rows[0]!.count,
      0,
    );
    await storage.deleteTable(actor, second.id, {
      expectedSchemaVersion: second.schemaVersion,
    });
    assert.equal((await databaseSummary()).rowCount, 0);
    assert.equal((await databaseSummary()).tableCount, 1);
    assert.equal((await databaseSummary()).lastDataChangeAt, deletedAt);
    const other = { ...actor, orgId: newId() };
    await assert.rejects(storage.listDatabases(other), {
      code: "RESOURCE_NOT_FOUND",
    });
    await assert.rejects(storage.listTables(other, database.id), {
      code: "RESOURCE_NOT_FOUND",
    });
  },
);
